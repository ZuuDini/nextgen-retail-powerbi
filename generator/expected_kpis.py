"""Answer key: computes every KPI the report shows, straight from the clean tables.

Each function here mirrors one measure in dax/measures.dax, with the same name and
the same definition. Milestone 3 of the build guide is "every card in Power BI
equals data/expected/kpis.json". If a number differs, the DAX or the cleanup is
wrong, not this file. That's the trace-every-number check.
"""

from __future__ import annotations

import pandas as pd


def enrich(clean: dict[str, pd.DataFrame]) -> tuple[pd.DataFrame, pd.DataFrame]:
    p = clean["products"].set_index("ProductKey")
    st = clean["stores"].set_index("StoreCode")
    cu = clean["customers"].set_index("CustomerKey")
    s = clean["sales"].copy()
    s["Year"] = pd.to_datetime(s["OrderDate"]).dt.year
    s["Region"] = s["StoreCode"].map(st["Region"])
    s["Category"] = s["ProductKey"].map(p["Category"])
    s["Segment"] = s["CustomerKey"].map(cu["Segment"])
    s["UnitCost"] = s["ProductKey"].map(p["UnitCost"])
    s["ListValue"] = s["Quantity"] * s["UnitPrice"]
    s["LineAmount"] = s["ListValue"] * (1 - s["DiscountPct"] / 100)
    s["LineCost"] = s["Quantity"] * s["UnitCost"]

    inv = clean["inventory"].copy()
    inv["Year"] = pd.to_datetime(inv["SnapshotDate"]).dt.year
    inv["Region"] = inv["StoreCode"].map(st["Region"])
    inv["Category"] = inv["ProductKey"].map(p["Category"])
    inv["InventoryValue"] = inv["OnHandUnits"] * inv["ProductKey"].map(p["UnitCost"])
    return s, inv


def sales_measures(s: pd.DataFrame, days: int) -> dict:
    pos = s[s["Quantity"] > 0]
    neg = s[s["Quantity"] < 0]
    total = s["LineAmount"].sum()
    gross = pos["LineAmount"].sum()
    cogs = s["LineCost"].sum()
    orders = pos["OrderID"].nunique()
    per_cust = pos.groupby("CustomerKey")["OrderID"].nunique()
    units = int(pos["Quantity"].sum())
    returned = int(-neg["Quantity"].sum())
    disc_amt = (pos["ListValue"] - pos["LineAmount"]).sum()
    return {
        "Total Sales": round(total, 2),
        "Gross Sales": round(gross, 2),
        "Returns Amount": round(-neg["LineAmount"].sum(), 2),
        "COGS": round(cogs, 2),
        "Gross Margin": round(total - cogs, 2),
        "Margin %": round((total - cogs) / total, 4) if total else None,
        "Units Sold": units,
        "Units Returned": returned,
        "Return Rate %": round(returned / units, 4) if units else None,
        "Orders": int(orders),
        "AOV": round(gross / orders, 2) if orders else None,
        "Customers": int(len(per_cust)),
        "Repeat Customers": int((per_cust >= 2).sum()),
        "Repeat Rate %": round((per_cust >= 2).mean(), 4) if len(per_cust) else None,
        "Avg Discount %": round(disc_amt / pos["ListValue"].sum(), 4),
        "_days": days,
    }


def inventory_measures(inv: pd.DataFrame, m: dict) -> dict:
    by_snap = inv.groupby("SnapshotDate")["InventoryValue"].sum()
    avg_inv = by_snap.mean()
    last = inv["SnapshotDate"].max()
    ending_units = int(inv.loc[inv["SnapshotDate"] == last, "OnHandUnits"].sum())
    cogs, days = m["COGS"], m.pop("_days")
    return {
        "Avg Inventory Value": round(avg_inv, 2),
        "Inventory Turnover": round(cogs / avg_inv, 2),
        "Days of Supply": round(avg_inv / (cogs / days), 1),
        "Ending On Hand Units": ending_units,
        "Sell-Through %": round(m["Units Sold"] / (m["Units Sold"] + ending_units), 4),
    }


def _days(year: int | None) -> int:
    if year is None:
        return 731
    return 366 if year == 2024 else 365


def block(s: pd.DataFrame, inv: pd.DataFrame | None, year: int | None) -> dict:
    m = sales_measures(s, _days(year))
    if inv is not None:
        m.update(inventory_measures(inv, m))
    else:
        m.pop("_days")
    return m


def compute(clean: dict[str, pd.DataFrame]) -> dict:
    s, inv = enrich(clean)
    tg = clean["targets"].copy()
    tg["Year"] = pd.to_datetime(tg["MonthStart"]).dt.year
    out: dict = {"_note": "Answer key generated by generator/expected_kpis.py. "
                          "Fractions are shown as decimals: 0.3125 = 31.25%."}

    out["All Years"] = block(s, inv, None)
    out["By Year"] = {str(y): block(s[s.Year == y], inv[inv.Year == y], y)
                      for y in (2024, 2025)}
    a, b = out["By Year"]["2024"]["Total Sales"], out["By Year"]["2025"]["Total Sales"]
    out["By Year"]["2025"]["Sales YoY %"] = round((b - a) / a, 4)

    out["By Region and Year"] = {}
    for r in sorted(s["Region"].unique()):
        out["By Region and Year"][r] = {}
        for y in (2024, 2025):
            m = block(s[(s.Region == r) & (s.Year == y)],
                      inv[(inv.Region == r) & (inv.Year == y)], y)
            target = tg[(tg.Region == r) & (tg.Year == y)]["TargetSales"].sum()
            m["Target Sales"] = round(target, 2)
            m["Sales vs Target %"] = round((m["Total Sales"] - target) / target, 4)
            out["By Region and Year"][r][str(y)] = m
        prev = out["By Region and Year"][r]["2024"]["Total Sales"]
        cur = out["By Region and Year"][r]["2025"]["Total Sales"]
        out["By Region and Year"][r]["2025"]["Sales YoY %"] = round((cur - prev) / prev, 4)

    out["By Segment and Year"] = {
        seg: {str(y): {k: v for k, v in block(s[(s.Segment == seg) & (s.Year == y)],
                                              None, y).items()
                       if k in ("Total Sales", "Customers", "Orders",
                                "Repeat Rate %", "AOV")}
              for y in (2024, 2025)}
        for seg in sorted(s["Segment"].unique())}

    out["By Category and Year"] = {
        cat: {str(y): {k: v for k, v in block(s[(s.Category == cat) & (s.Year == y)],
                                              None, y).items()
                       if k in ("Total Sales", "Margin %", "Avg Discount %", "Units Sold")}
              for y in (2024, 2025)}
        for cat in sorted(s["Category"].unique())}

    names = clean["products"].set_index("ProductKey")["ProductName"]
    top = (s[s.Year == 2025].groupby("ProductKey")["LineAmount"].sum()
           .sort_values(ascending=False).head(5))
    out["Top 5 Products 2025"] = [
        {"Rank": i + 1, "ProductKey": k, "ProductName": names[k],
         "Total Sales": round(v, 2)} for i, (k, v) in enumerate(top.items())]

    out["Row Counts"] = {
        "FactSales": len(clean["sales"]), "FactInventory": len(clean["inventory"]),
        "DimProduct": len(clean["products"]), "DimCustomer": len(clean["customers"]),
        "DimStore": len(clean["stores"]), "RegionTargets": len(clean["targets"]),
        "DimDate": 731,
    }
    return out
